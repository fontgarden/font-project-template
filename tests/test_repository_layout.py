"""Keep the repository small: every tracked file must have an allowed place.

This test fails when a commit adds a file that the layout does not allow, for
example a worklog, a handoff, a report, a receipt or a dated document. To add a
new kind of file, change LAYOUT or OPTIONAL in the same commit and say why in the commit
message. AGENTS.md describes the layout for people and agents.

Every LAYOUT pattern must match at least one tracked file. When you remove the
last file of a kind, remove its pattern in the same commit.
"""
import re
import subprocess
import unittest
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]

# Allowed paths, as PurePath.full_match patterns. `*` does not match `/`; `**`
# matches any depth.
LAYOUT = [
    # Root: the Google Fonts template files, plus the agent guide and status.
    '.gitignore', 'AGENTS.md', 'AUTHORS.txt', 'CONTRIBUTORS.txt', 'Makefile',
    'OFL.txt', 'README.md', 'STATUS.md', 'requirements.in', 'requirements.txt',
    '.github/workflows/*.yaml',
    # Agent files: task contracts, and the OMP rules link to AGENTS.md.
    '.agents/tasks/*.md', '.omp/RULES.md',
    # Sources.
    'sources/config.yaml', 'sources/held-out-glyphs.toml', 'CONTEXT.md',
    'sources/*.ufo/**',
    # Tests of the repository itself. The tools are in fontgarden-tools.
    'tests/test_*.py',
    # Documentation.
    'documentation/*.md',
]

# Allowed paths that a project does not need. No file has to match them.
OPTIONAL = [
    # More than one master.
    'sources/*.designspace',
    # The specimen that the font was traced from, and its glyph labels.
    'sources/specimen/*',
    # Text samples of this project for `fgtools proof-web`.
    'sources/proof-samples.toml',
    # Tools that only this font needs.
    'scripts/*.py',
    # The Google Fonts article and the DesignBot scripts of the images.
    'documentation/article/**', 'documentation/readme-images/*.rs',
]

# Names that mark a record of work rather than a maintained document.
RECORD_NAME = re.compile(r'worklog|handoff|report|receipt|\d{4}-\d{2}-\d{2}', re.I)

# STATUS.md is generated by `make status`.
GENERATED = {'STATUS.md'}

# Large files make every clone of the history larger, also after they are
# removed. Rendered output goes to out/. A specimen scan can be larger.
MAX_FILE_BYTES = 500_000
MAX_SPECIMEN_BYTES = 8_000_000


def tracked():
    out = subprocess.run(['git', 'ls-files'], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout
    return [line for line in out.splitlines() if (ROOT / line).exists()]


def allowed(path, pattern):
    return PurePosixPath(path).full_match(pattern)


def problems(path):
    found = []
    if not any(allowed(path, pattern) for pattern in LAYOUT + OPTIONAL):
        found.append('no allowed place in LAYOUT')
    size = (ROOT / path).stat().st_size
    limit = MAX_SPECIMEN_BYTES if path.startswith('sources/specimen/') else MAX_FILE_BYTES
    if size > limit:
        found.append(f'{size} bytes, more than {limit}')
    if path in GENERATED:
        return found
    name = PurePosixPath(path).name
    if name.endswith(('.md', '.txt', '.html')) and RECORD_NAME.search(name):
        found.append('name of a work record')
    return found


class RepositoryLayout(unittest.TestCase):
    def test_every_file_has_an_allowed_place(self):
        failures = []
        for path in tracked():
            for problem in problems(path):
                failures.append(f'{path}: {problem}')
        self.assertFalse(failures, '\n' + '\n'.join(failures) +
                         '\nSee tests/test_repository_layout.py and AGENTS.md.')

    def test_every_pattern_matches_a_file(self):
        files = tracked()
        unused = [p for p in LAYOUT if not any(allowed(f, p) for f in files)]
        self.assertFalse(unused, f'Remove these patterns from LAYOUT: {unused}')


if __name__ == '__main__':
    unittest.main()
